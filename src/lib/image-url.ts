/** Serve our own uploaded images through the same-origin, cached R2 proxy.
 * Canvas exports can then embed them even when the public bucket has no CORS rules.
 * Leave third-party artwork and local draft images untouched.
 */
export function getItemImageUrl(
  src: string,
  assetBaseUrl = process.env.NEXT_PUBLIC_R2_ASSET_BASE_URL || "",
): string {
  if (!assetBaseUrl || !src.startsWith("https://")) return src;
  try {
    const assetBase = new URL(assetBaseUrl);
    const image = new URL(src);
    const prefix = `${assetBase.pathname.replace(/\/+$/, "")}/`;
    if (image.origin !== assetBase.origin || !image.pathname.startsWith(prefix)) return src;
    const key = image.pathname.slice(prefix.length);
    // Only immutable upload keys generated by this app can use the proxy.
    if (!/^items\/[a-f0-9]{24}\.(webp|png|jpg)$/.test(key)) return src;
    return `/api/cdn/${key}`;
  } catch {
    return src;
  }
}
